#!/usr/bin/env node
// Baked courses → lazy-loaded classic-script packs: assets/track-<id>.js sets
// (window.TR_PACKS ||= {})['track-<id>'] = { track: <baked json> }. The game injects the script when a course
// is chosen, so index.html stays small and file:// still works.
//   node tools/pack-tracks.mjs [<id>…]   (default: every data/tracks/*.json except the gray box)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(ROOT, 'data', 'tracks');
const args = process.argv.slice(2);
const ids = args.length ? args : fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5));
for (const id of ids) {
  const json = fs.readFileSync(path.join(dir, id + '.json'), 'utf8');
  const out = path.join(ROOT, 'assets', `track-${id}.js`);
  fs.writeFileSync(out, `/* Spa City Tub Rally course "${id}" (baked by tools/track/bake.mjs; streets © OpenStreetMap contributors, ODbL 1.0; elevation USGS 3DEP). */\n(window.TR_PACKS=window.TR_PACKS||{})[${JSON.stringify('track-' + id)}]={track:${json}};\n`);
  console.log(path.relative(ROOT, out), (fs.statSync(out).size / 1024).toFixed(1), 'KB');
}
// manifest of built courses (every track pack present in assets/; the gray box is a dev course, not listed)
const built = fs.readdirSync(path.join(ROOT, 'assets')).filter((f) => f.startsWith('track-') && f.endsWith('.js')).map((f) => f.slice(6, -3)).filter((id) => id !== 'graybox');
const info = {};
for (const id of built) {
  const f = path.join(dir, id + '.json');
  if (!fs.existsSync(f)) continue;
  const j = JSON.parse(fs.readFileSync(f, 'utf8')), r = (j.meta && j.meta.route) || {};
  info[id] = { length: Math.round(j.length), real: r.realLength ? Math.round(r.realLength) : null, climb: j.stats ? j.stats.climb : null };
}
const lengths = Object.fromEntries(Object.entries(info).map(([k, v]) => [k, v.length]));
fs.writeFileSync(path.join(ROOT, 'assets', 'tracks.js'), `/* Built courses (generated by tools/pack-tracks.mjs). */
window.TR_BUILT=${JSON.stringify(built)};window.TR_LENGTHS=${JSON.stringify(lengths)};window.TR_INFO=${JSON.stringify(info)};
`);
console.log('assets/tracks.js', built.join(', '));
